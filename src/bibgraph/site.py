def esc(value: object) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def rel(depth: int, target: str) -> str:
    """Relative URL from a page `depth` directories below the site root.

    Relative throughout so the same build works at localhost and under
    https://<owner>.github.io/<repository>/ without rewriting.
    """
    prefix = "../" * depth
    return (prefix + target.lstrip("/")) if target != "/" else (prefix or "./")


def work_href(depth: int, alias: str) -> str:
    return rel(depth, f"works/{util.safe_path_segment(alias)}/")


def node_href(depth: int, view: DagView, node_id: str) -> str:
    node = view.nodes.get(node_id)
    if node is not None and node.kind == "choice":
        return rel(depth, f"dependencies/#{util.safe_path_segment(node_id)}")
    return work_href(depth, node_id)


NAV = (
    ("", "Overview"),
    ("dependencies/", "Dependencies"),
    ("works/", "Works"),
    ("graph/", "Citation graph"),
    ("survey/", "Survey"),
    ("reports/", "Reports"),
)


def page(title: str, body: str, depth: int, *, subtitle: str = "",
         public: bool = False) -> str:
    nav = "".join(
        f'<a href="{esc(rel(depth, href) if href else rel(depth, "index.html"))}">{esc(label)}</a>'
        for href, label in NAV)
    build_label = "public build" if public else "local build"
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)} — bibgraph</title>
<link rel="stylesheet" href="{esc(rel(depth, 'site.css'))}">
</head>
<body>
<header class="site">
<nav aria-label="Main">{nav}</nav>
</header>
<main>
<h1>{esc(title)}</h1>
{f'<p class="muted">{esc(subtitle)}</p>' if subtitle else ''}
{body}
</main>
<footer class="site">
Generated by bibgraph {esc(util.GENERATOR_VERSION)} ({esc(build_label)}) at {esc(util.now_iso())}.
Computed observations are labelled separately from human interpretation.
</footer>
<script src="{esc(rel(depth, 'site.js'))}" defer></script>
</body>
</html>
"""


def badge(value: str, label: str | None = None) -> str:
    slug = util.safe_path_segment(str(value)).lower().replace(".", "-")
    return f'<span class="badge {esc(slug)}">{esc(label or value)}</span>'


def table(headers: list[str], rows: list[list[str]], empty: str = "None.") -> str:
    if not rows:
        return f'<p class="muted">{esc(empty)}</p>'
    head = "".join(f"<th scope=\"col\">{esc(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def definition_list(pairs: list[tuple[str, str]]) -> str:
    items = "".join(f"<dt>{esc(k)}</dt><dd>{v}</dd>" for k, v in pairs)
    return f"<dl>{items}</dl>"



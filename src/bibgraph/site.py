"""Deterministic static site generation.

Small explicit rendering functions, `html.escape` on every interpolated value,
relative URLs throughout, and no template package or CDN asset. Every page is
complete without JavaScript; the one script is progressive enhancement.
"""

from __future__ import annotations

import dataclasses
import html

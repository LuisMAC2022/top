def render_dag_svg(view: DagView, depth: int, corpus: Corpus) -> str:
    """Deterministic inline SVG. Edge meaning is carried by dash and colour."""
    layout = view.layout()
    positions = layout["positions"]
    box_w, box_h = 168, 40
    alias_titles = {}
    by_id = corpus.by_id()
    for node_id, node in view.nodes.items():
        work = by_id.get(node.ref or "") or corpus.by_alias().get(node.ref or "")
        alias_titles[node_id] = work.display_title if work else node.label

    parts = [
        f'<svg class="dag" viewBox="0 0 {layout["width"]} {layout["height"]}" '
        f'width="{layout["width"]}" height="{layout["height"]}" role="img" '
        'aria-labelledby="dag-title dag-desc" xmlns="http://www.w3.org/2000/svg">',
        '<title id="dag-title">Dependency graph</title>',
        '<desc id="dag-desc">A typed directed acyclic graph. The same relationships '
        'are listed as text in the adjacency list below this diagram.</desc>',
        '<defs>',
    ]
    for edge_type, style in sorted(EDGE_STYLE.items()):
        parts.append(
            f'<marker id="arrow-{esc(edge_type)}" viewBox="0 0 10 10" refX="9" refY="5" '
            f'markerWidth="6" markerHeight="6" orient="auto-start-reverse">'
            f'<path d="M 0 0 L 10 5 L 0 10 z" fill="{esc(style["color"])}"/></marker>')
    parts.append("</defs>")

    for edge in sorted(view.edges, key=lambda e: (e.type, e.source, e.target)):
        if edge.source not in positions or edge.target not in positions:
            continue
        style = EDGE_STYLE.get(edge.type, EDGE_STYLE["prerequisite"])
        x1 = positions[edge.source]["x"] + box_w / 2
        y1 = positions[edge.source]["y"] + box_h
        x2 = positions[edge.target]["x"] + box_w / 2
        y2 = positions[edge.target]["y"]
        dash = f' stroke-dasharray="{esc(style["dash"])}"' if style["dash"] else ""
        parts.append(
            f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            f'stroke="{esc(style["color"])}" stroke-width="{style["width"]}"{dash} '
            f'marker-end="url(#arrow-{esc(edge.type)})">'
            f'<title>{esc(edge.source)} {esc(edge.type)} {esc(edge.target)}</title></line>')

    for node_id in sorted(positions):
        node = view.nodes[node_id]
        pos = positions[node_id]
        shape = ('rx="18"' if node.kind == "choice"
                 else 'rx="2"' if node.kind == "collection" else 'rx="6"')
        stroke = "#8a5a00" if node.kind == "choice" else "#1f4e79"
        dash = ' stroke-dasharray="4 2"' if node.kind == "choice" else ""
        label = node_id if len(node_id) <= 22 else node_id[:21] + "…"
        parts.append(
            f'<a href="{esc(node_href(depth, view, node_id))}">'
            # Filled with the page background so edges pass behind the label
            # rather than through it; the fill follows the colour scheme.
            f'<rect x="{pos["x"]}" y="{pos["y"]}" width="{box_w}" height="{box_h}" '
            f'{shape} fill="var(--bg, #ffffff)" stroke="{esc(stroke)}" '
            f'stroke-width="1.6"{dash}/>'
            f'<text x="{pos["x"] + 10}" y="{pos["y"] + 25}" fill="currentColor">'
            f'{esc(label)}</text>'
            f'<title>{esc(alias_titles.get(node_id, node_id))}</title></a>')
    parts.append("</svg>")
    return "\n".join(parts)


def render_legend() -> str:
    items = "".join(
        f'<li>{badge(t)} <span class="muted">stroke: '
        f'{esc(s["dash"] or "solid")}, colour {esc(s["color"])}</span></li>'
        for t, s in sorted(EDGE_STYLE.items()))
    return ('<h3>Edge types</h3><ul class="plain legend">' + items + "</ul>"
            '<p class="muted">Shape and dash pattern carry the same information as '
            'colour, so the diagram is readable without colour perception.</p>')



@dataclasses.dataclass
class SiteData:
    corpus: Corpus
    deps: Dependencies
    profile: dict
    view: DagView
    artifacts: dict[str, dict]          # asset_id -> ledger row
    documents: dict[str, dict]          # work id -> extracted document
    analysis: dict | None = None
    survey: dict | None = None
    edges: list[dict] = dataclasses.field(default_factory=list)
    reviews: dict[str, dict] = dataclasses.field(default_factory=dict)
    public: bool = False


def build_index(data: SiteData) -> str:
    corpus, view = data.corpus, data.view
    unverified = [w for w in corpus.works if w.metadata_status == "unverified"]
    unresolved = [c for c in view.choices() if view.selection(c.id) is None]

    status_rows = []
    for work in sorted(corpus.works, key=lambda w: w.primary_alias):
        rows = [data.artifacts.get(a.id) for a in work.assets]
        downloaded = sum(1 for r in rows if r and r["status"] == "downloaded")
        doc = data.documents.get(work.id)
        status_rows.append([
            f'<a href="{esc(work_href(0, work.primary_alias))}">{esc(work.primary_alias)}</a>',
            esc(work.display_title),
            badge(work.work_type),
            badge(work.rights.access),
            badge(work.metadata_status),
            f"{downloaded}/{len(work.assets)}",
            badge(doc["overall_status"]) if doc else badge("not_extracted"),
        ])

    notice = ""
    if not corpus.source.get("supplied", False):
        notice = (
            '<div class="notice"><strong>Incomplete corpus.</strong> The source '
            'catalogue was not supplied, so every record below is a structural '
            'placeholder with no verified metadata. Nothing here has been invented '
            'to fill the gap.</div>')
    if not view.edges:
        notice += (
            '<div class="notice"><strong>Empty dependency graph.</strong> No typed '
            'edge has been recorded, so navigation cannot yet show prerequisites. '
            'The relationship diagram must be supplied and reviewed.</div>')

    choices_html = "".join(
        f'<li><a href="{esc(rel(0, "dependencies/#" + util.safe_path_segment(c.id)))}">'
        f'{esc(c.label)}</a> — {" or ".join(esc(o) for o in c.options)} '
        f'{badge("unresolved")}</li>' for c in unresolved)

    body = f"""
{notice}
<h2>Corpus status</h2>
{table(["Alias", "Title", "Type", "Access", "Metadata", "Acquired", "Extraction"], status_rows)}
<h2>Unresolved choices</h2>
{f'<ul class="plain">{choices_html}</ul>' if unresolved
 else '<p class="muted">Every alternative has been selected in the reading profile.</p>'}
<p class="muted">An unresolved choice is left unresolved. The reading order stops
at the choice and offers both branches rather than picking one.</p>
<h2>Reading profile</h2>
{definition_list([(k, esc(v) if v else '<em>unselected</em>')
                  for k, v in sorted(data.profile.items())] or [("(none)", "no choices defined")])}
<h2>Summary</h2>
{definition_list([
    ("Works", str(len(corpus.works))),
    ("Verified metadata", f"{len(corpus.works) - len(unverified)} of {len(corpus.works)}"),
    ("Dependency nodes", str(len(view.nodes))),
    ("Dependency edges", str(len(view.edges))),
    ("Assets declared", str(sum(len(w.assets) for w in corpus.works))),
    ("Assets downloaded", str(sum(1 for r in data.artifacts.values()
                                  if r["status"] == "downloaded"))),
])}
"""
    return page("Corpus overview", body, 0, public=data.public,
                subtitle="Local bibliography graph. Machine observations only; "
                         "reading judgement stays human.")


def build_dependencies(data: SiteData) -> str:
    view, corpus = data.view, data.corpus
    if view.edges:
        svg = render_dag_svg(view, 1, corpus)
    else:
        svg = ('<p class="empty">No dependency edge has been recorded, so there is '
               'no graph to draw. This is reported rather than rendered as an empty '
               'diagram that might be mistaken for a finished one.</p>')

    adjacency_rows = []
    for row in view.adjacency_text():
        prereqs = ", ".join(
            f'<a href="{esc(node_href(1, view, p["node"]))}">{esc(p["node"])}</a> '
            f'<span class="muted">({esc(p["type"])})</span>' for p in row["prerequisites"])
        dependents = ", ".join(
            f'<a href="{esc(node_href(1, view, d["node"]))}">{esc(d["node"])}</a> '
            f'<span class="muted">({esc(d["type"])})</span>' for d in row["dependents"])
        adjacency_rows.append([
            f'<a href="{esc(node_href(1, view, row["node"]))}">{esc(row["node"])}</a>',
            badge(row["kind"]),
            prereqs or '<span class="muted">none</span>',
            dependents or '<span class="muted">none</span>',
        ])

    try:
        order = view.reading_sequence()
        tree_rows = [
            [f'<a href="{esc(node_href(1, view, n))}">{esc(n)}</a>',
             str(view.layers().get(n, 0)),
             " &rsaquo; ".join(esc(p) for p in view.canonical_path(n))]
            for n in order]
    except ValueError as exc:
        tree_rows = []
        adjacency_rows.insert(0, [esc(str(exc)), "", "", ""])

    choice_sections = []
    for choice in view.choices():
        selected = view.selection(choice.id)
        branch_html = "".join(
            f"<li><a href=\"{esc(node_href(1, view, b.option))}\">{esc(b.option)}</a>"
            f"{' ' + badge('selected') if b.option == selected else ''}"
            f"<br><span class=\"muted\">unlocks: "
            f"{esc(', '.join(b.reachable) or 'nothing downstream')}</span></li>"
            for b in view.branches_for(choice.id))
        choice_sections.append(
            f'<section id="{esc(util.safe_path_segment(choice.id))}">'
            f"<h3>{esc(choice.label)} {badge('unresolved') if not selected else badge('resolved')}</h3>"
            f'<p class="muted">{esc(choice.note or "")}</p>'
            f'<ul class="plain">{branch_html}</ul>'
            f'<p class="muted">Select a branch by editing '
            f'<code>config/reading-profile.json</code>; the data model will not '
            f'choose one on your behalf.</p></section>')

    body = f"""
<h2>Typed graph</h2>
{svg}
{render_legend()}
<h2>Choices</h2>
{"".join(choice_sections) or '<p class="muted">No choice nodes.</p>'}
<h2>Tree projection and reading order</h2>
<p class="muted">A DAG node can have several parents, so the canonical path below
is one deterministic display path, not the only one. Each work page lists
<strong>all</strong> prerequisites separately.</p>
{table(["Node", "Depth", "Canonical path"], tree_rows)}
<h2>Adjacency list</h2>
<p class="muted">The same information as the diagram, in text.</p>
{table(["Node", "Kind", "Prerequisites", "Dependents"], adjacency_rows)}
"""
    return page("Dependencies", body, 1, public=data.public)


def build_works_index(data: SiteData) -> str:
    rows = []
    for work in sorted(data.corpus.works, key=lambda w: w.primary_alias):
        rows.append([
            f'<a href="{esc(work_href(1, work.primary_alias))}">{esc(work.primary_alias)}</a>',
            esc(work.display_title),
            badge(work.work_type),
            badge(work.rights.access),
            esc(", ".join(work.authors) or "—"),
            esc(work.year or "—"),
        ])
    body = f"<h2>All works</h2>{table(['Alias', 'Title', 'Type', 'Access', 'Authors', 'Year'], rows)}"
    return page("Works", body, 1, public=data.public)


KESHAV_TEMPLATE = {
    "pass_status": "unread",
    "five_cs": {"category": "", "context": "", "correctness": "",
                "contributions": "", "clarity": ""},
    "decision": {"continue": None, "reason": ""},
    "pass_two": {"figures": "", "evidence": "", "assumptions": "",
                 "unclear_terms": "", "important_references": ""},
    "pass_three": {"reconstructed_argument": "", "challenged_assumptions": "",
                   "weaknesses": "", "extensions": "", "reproducibility": ""},
}


def build_work_page(data: SiteData, work: Work) -> str:
    view = data.view
    alias = work.primary_alias
    depth = 2
    doc = data.documents.get(work.id)

    asset_rows = []
    for asset in work.assets:
        row = data.artifacts.get(asset.id)
        status = row["status"] if row else "not_requested"
        link = (f'<a href="{esc(asset.url)}" rel="noopener noreferrer">source</a>'
                if asset.url else '<span class="muted">—</span>')
        local = "—"
        if row and row["status"] == "downloaded" and not data.public:
            local = f'<code>{esc(row["path"])}</code>'
        elif row and row["status"] == "downloaded":
            local = '<span class="muted">held privately</span>'
        asset_rows.append([
            badge(asset.role), badge(asset.intent), badge(status), link, local,
            f'<code>{esc((row["sha256"] or "")[:12])}</code>' if row and row["sha256"] else "—",
            esc((row["reason"] or "") if row else ""),
        ])

    upstream = view.upstream(alias) if alias in view.nodes else []
    downstream = view.downstream(alias) if alias in view.nodes else []
    all_prereqs = view.all_prerequisites(alias) if alias in view.nodes else []
    alternatives = [e for e in (view.outgoing(alias) + view.incoming(alias))
                    if e.type in ("backup", "validates")] if alias in view.nodes else []

    def link_list(nodes: list[str]) -> str:
        if not nodes:
            return '<p class="muted">None.</p>'
        return ('<ul class="plain">' + "".join(
            f'<li><a href="{esc(node_href(depth, view, n))}">{esc(n)}</a></li>'
            for n in nodes) + "</ul>")

    choice = view.choice_for_option(alias) if alias in view.nodes else None
    choice_html = ""
    if choice is not None:
        others = [o for o in choice.options if o != alias]
        other_links = ", ".join(
            '<a href="%s">%s</a>' % (esc(work_href(depth, o)), esc(o)) for o in others)
        choice_link = esc(rel(depth, "dependencies/#" + util.safe_path_segment(choice.id)))
        unselected = ("Neither has been selected."
                      if view.selection(choice.id) is None else "")
        choice_html = (
            f'<div class="notice"><strong>Alternative.</strong> This work is one arm '
            f'of <a href="{choice_link}">{esc(choice.label)}</a>; the other '
            f'{"is" if len(others) == 1 else "are"} {other_links}. {unselected}</div>')

    previous, nxt = view.prev_next(alias) if alias in view.nodes else (None, None)
    pager = (
        '<nav class="pager" aria-label="Reading order">'
        + (f'<a href="{esc(node_href(depth, view, previous))}">&laquo; {esc(previous)}</a>'
           if previous else '<span class="muted">start of order</span>')
        + (f'<a href="{esc(node_href(depth, view, nxt))}">{esc(nxt)} &raquo;</a>'
           if nxt else '<span class="muted">end of order</span>')
        + "</nav>")

    extraction_html = render_extraction(doc, data.public) if doc else (
        '<p class="empty">Not extracted yet. No field is shown, because an absent '
        'value must never be displayed as an empty success.</p>')

    review = data.reviews.get(work.id, {}).get("payload") or KESHAV_TEMPLATE
    review_json = util.canonical_json({"work_id": work.id, "alias": alias, **review})
    area_id = f"review-{util.safe_path_segment(alias)}"
    review_html = f"""
<p class="muted">The machine performs the mechanical part of the first pass only.
The five Cs are your judgement, not an inference.</p>
<form method="post" action="#" onsubmit="return false">
<label for="{esc(area_id)}"><strong>Keshav review record (JSON)</strong></label>
<textarea id="{esc(area_id)}" name="review" spellcheck="false">{esc(review_json)}</textarea>
</form>
<p>
<button type="button" data-export-target="{esc(area_id)}"
        data-filename="{esc(alias)}.json" hidden>Download JSON</button>
<span class="muted">Select the text above and save it as
<code>annotations/{esc(alias)}.json</code>, then run
<code>bibgraph annotate {esc(alias)} annotations/{esc(alias)}.json</code>.
A download button appears if JavaScript is available; the copy-and-save route
works without it.</span>
</p>
"""

    rights_rows = [
        ("Access", badge(work.rights.access)),
        ("Licence", esc(work.rights.license or "not recorded")),
        ("Licence evidence",
         f'<a href="{esc(work.rights.license_evidence_url)}" rel="noopener noreferrer">evidence</a>'
         if work.rights.license_evidence_url else '<span class="muted">none recorded</span>'),
        ("Local storage", "permitted" if work.rights.local_storage_allowed else "not permitted"),
        ("Publish metadata", "yes" if work.rights.publish_metadata else "no"),
        ("Publish abstract", "yes" if work.rights.publish_abstract else "no"),
        ("Publish full text", "yes" if work.rights.publish_fulltext else "no"),
    ]

    body = f"""
{choice_html}
<h2>Citation</h2>
{definition_list([
    ("Alias", esc(alias)),
    ("Canonical id", f"<code>{esc(work.id)}</code>"),
    ("Title", esc(work.display_title)),
    ("Authors", esc("; ".join(work.authors) or "not recorded")),
    ("Year", esc(work.year or "not recorded")),
    ("Type", badge(work.work_type)),
    ("Metadata", badge(work.metadata_status)),
])}
<h2>Access and rights</h2>
{definition_list(rights_rows)}
<h2>Assets</h2>
{table(["Role", "Intent", "Status", "Source", "Local copy", "SHA-256", "Note"], asset_rows)}
<h2>Dependencies</h2>
<h3>Upstream prerequisites (direct)</h3>
{link_list(upstream)}
<h3>All prerequisites (transitive)</h3>
{link_list(all_prereqs)}
<h3>Downstream dependents (direct)</h3>
{link_list(downstream)}
<h3>Alternatives, backups and validations</h3>
{table(["From", "Type", "To"],
       [[f'<a href="{esc(node_href(depth, view, e.source))}">{esc(e.source)}</a>',
         badge(e.type),
         f'<a href="{esc(node_href(depth, view, e.target))}">{esc(e.target)}</a>']
        for e in alternatives])}
<h2>First-pass extraction</h2>
{extraction_html}
<h2>Keshav review</h2>
{review_html}
{pager}
"""
    return page(f"{alias} — {work.display_title}", body, depth, public=data.public)


def render_extraction(doc: dict, public: bool) -> str:
    """Render extracted fields, always with state, method, confidence and source."""
    rows = []
    for name in ("title", "abstract", "introduction", "conclusion", "references"):
        field = doc.get("fields", {}).get(name)
        if not field:
            rows.append([esc(name), badge("not_extracted"), "—", "—", "—"])
            continue
        status = field.get("status", "failed")
        showable = status == "present" and (not public or doc.get("publishable", {}).get(name))
        if showable:
            text = field.get("text") or ""
            preview = text if len(text) <= 600 else text[:600] + "…"
            shown = f"<details><summary>show</summary><pre>{esc(preview)}</pre></details>"
        elif status == "present":
            shown = '<span class="muted">held privately; not cleared for publication</span>'
        else:
            shown = f'<span class="muted">{esc(field.get("reason") or "no value")}</span>'
        source = field.get("source") or {}
        rows.append([
            esc(name),
            badge(status),
            f'{field.get("confidence", 0):.2f}' if field.get("confidence") is not None else "—",
            f'<code>{esc(field.get("method") or "—")}</code>',
            shown + (f'<br><span class="muted">pages {esc(source.get("pages"))}, '
                     f'sha {esc((source.get("asset_sha256") or "")[:12])}</span>'
                     if source else ""),
        ])

    sections = doc.get("sections") or []
    section_html = "".join(
        f'<li style="margin-left:{max(0, (s.get("level", 1) - 1)) * 1.2:.1f}rem">'
        f'{esc(s.get("number") or "")} {esc(s.get("title"))} '
        f'<span class="muted">(level {esc(s.get("level"))}, '
        f'confidence {s.get("confidence", 0):.2f})</span></li>' for s in sections)

    warnings = doc.get("warnings") or []
    warning_html = "".join(f"<li>{esc(w)}</li>" for w in warnings)

    return f"""
{definition_list([("Overall", badge(doc.get("overall_status", "unknown"))),
                  ("Adapter", f'<code>{esc(doc.get("adapter"))}</code>'),
                  ("Work type", badge(doc.get("work_type", "unknown")))])}
{table(["Field", "State", "Confidence", "Method", "Evidence"], rows)}
<h3>Section hierarchy</h3>
{f'<ul class="plain">{section_html}</ul>' if sections
 else '<p class="muted">No section tree was produced.</p>'}
<h3>Extraction warnings</h3>
{f"<ul>{warning_html}</ul>" if warnings else '<p class="muted">None.</p>'}
"""


def build_empty_state(title: str, explanation: str, depth: int, public: bool) -> str:
    return page(title, f'<p class="empty">{esc(explanation)}</p>', depth, public=public)


def build_reports_page(data: SiteData, reports: list[dict]) -> str:
    rows = []
    for report in reports:
        rows.append([
            esc(report.get("name")),
            esc(report.get("command")),
            esc(report.get("generated_at")),
            esc(report.get("summary")),
        ])
    body = f"""
<h2>Run reports</h2>
<p class="muted">Local filesystem paths, cache payloads and contact details are
removed from this view.</p>
{table(["Report", "Command", "Generated", "Summary"], rows,
       empty="No run has been recorded yet.")}
"""
    return page("Reports", body, 1, public=data.public)


